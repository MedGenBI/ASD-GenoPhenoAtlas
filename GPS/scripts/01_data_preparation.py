import argparse
import os
import sys


CODE_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if CODE_ROOT not in sys.path:
    sys.path.insert(0, CODE_ROOT)

from src.config import (
    BINARY_TRAITS,
    CONTINUOUS_TRAITS,
    MISSINGNESS_THRESHOLD,
    OUTPUT_DIR,
    PHENOTYPE_PATH,
    TRAIT_ID_TO_LABEL,
)
from src.dataloader import (
    GENE_ASSOCIATION_COUNTS_FILENAME,
    PHENOTYPE_ASSOCIATION_COUNTS_FILENAME,
    PREPROCESSOR_FILENAME,
    PROCESSED_PHENOTYPE_FILENAME,
    generate_association_count_summaries,
    load_raw_data,
)
from src.preprocessor import PhenotypePreprocessor


def main():
    parser = argparse.ArgumentParser(
        description="Prepare association counts and derivation phenotypes."
    )
    parser.add_argument(
        "--association-file",
        required=True,
        help="Association-results table generated by the GPA workflow.",
    )
    parser.add_argument(
        "--outdir",
        default=None,
        help="Project output root; defaults to GPS_OUTPUT_DIR or ./output.",
    )
    args = parser.parse_args()

    project_output_dir = os.path.abspath(args.outdir or OUTPUT_DIR)
    step_dir = os.path.join(project_output_dir, "01_data_preparation")
    processed_data_dir = os.path.join(step_dir, "processed_data")
    os.makedirs(processed_data_dir, exist_ok=True)

    association_file = os.path.abspath(args.association_file)
    if not PHENOTYPE_PATH:
        raise ValueError("Set GPS_PHENOTYPE_PATH before running this script.")

    print(f"Project output: {project_output_dir}")
    print("Loading association and phenotype tables...")
    _, association, phenotype = load_raw_data(association_file, PHENOTYPE_PATH)

    print("Writing association-count summaries...")
    gene_counts, phenotype_counts = generate_association_count_summaries(
        association
    )
    gene_counts_path = os.path.join(
        processed_data_dir, GENE_ASSOCIATION_COUNTS_FILENAME
    )
    phenotype_counts_path = os.path.join(
        processed_data_dir, PHENOTYPE_ASSOCIATION_COUNTS_FILENAME
    )
    gene_counts.to_csv(gene_counts_path)
    phenotype_counts.rename(index=TRAIT_ID_TO_LABEL).to_csv(phenotype_counts_path)

    print("Filtering samples and applying rank-based INT...")
    preprocessor = PhenotypePreprocessor(
        continuous_traits=CONTINUOUS_TRAITS,
        binary_traits=BINARY_TRAITS,
        missing_threshold=MISSINGNESS_THRESHOLD,
    )
    processed = preprocessor.fit_transform(phenotype)

    processed_path = os.path.join(
        processed_data_dir, PROCESSED_PHENOTYPE_FILENAME
    )
    model_path = os.path.join(processed_data_dir, PREPROCESSOR_FILENAME)
    processed.to_csv(processed_path, index=False)
    preprocessor.save(model_path)

    print(f"Processed phenotype table: {processed_path}")
    print(f"Preprocessor model: {model_path}")


if __name__ == "__main__":
    main()
